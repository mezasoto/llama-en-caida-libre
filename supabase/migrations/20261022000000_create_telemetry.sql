create table if not exists public.telemetry (
  id bigint generated by default as identity primary key,
  device_id text not null check (char_length(device_id) between 1 and 64),
  temperature_c double precision not null check (temperature_c between -100 and 1000),
  smoke_ppm double precision not null check (smoke_ppm between 0 and 1000000),
  flame_detected boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists telemetry_created_at_idx
  on public.telemetry (created_at desc);

create index if not exists telemetry_device_created_at_idx
  on public.telemetry (device_id, created_at desc);

alter table public.telemetry enable row level security;